// Helper to compile regex and safely apply ruby tags for Furigana
export function addFuriganaHtml(text: string): string {
  if (!text) return "";
  const sortedKeys = Object.keys(furiganaDict).sort((a, b) => b.length - a.length);
  const escapedKeys = sortedKeys.map(k => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
  const regex = new RegExp("(" + escapedKeys.join("|") + ")", "g");
  return text.replace(regex, match => `<ruby>${match}<rt>${furiganaDict[match]}</rt></ruby>`);
}
