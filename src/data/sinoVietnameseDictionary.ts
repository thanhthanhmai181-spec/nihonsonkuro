/**
 * Get Sino-Vietnamese reading for a single Kanji character
 */
export function getSingleKanjiSino(char: string, fallbackMap?: Record<string, string>): string {
  if (fallbackMap && fallbackMap[char]) {
    return fallbackMap[char];
  }
  return SINO_VIETNAMESE_DICTIONARY[char] || "";
}

/**
 * Get formatted Sino-Vietnamese reading for a Japanese word (e.g. "禁止" -> "(Cấm - Chỉ)")
 */
export function getWordSinoVietnameseString(
  word: string, 
  fallbackMap?: Record<string, string>
): string {
  const kanjiRegex = /[\u4E00-\u9FAF\u3400-\u4DBF]/g;
  const matches = word.match(kanjiRegex);
  if (!matches || matches.length === 0) return "";

  const parts = matches
    .map(char => {
      const val = (fallbackMap && fallbackMap[char]) || SINO_VIETNAMESE_DICTIONARY[char] || "";
      if (!val) return "";
      return val.charAt(0).toUpperCase() + val.slice(1).toLowerCase();
    })
    .filter(Boolean);

  if (parts.length === 0) return "";
  return `(${parts.join(" - ")})`;
}
